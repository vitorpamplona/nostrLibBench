import { CLIENTS } from './clients.mjs';
import { readFileSync } from 'node:fs';
const C = CLIENTS.find(c => c.id === process.argv[2]);
const wl = process.argv[3] ?? 'smoke';
const m = JSON.parse(readFileSync('../.corpus/manifest.json','utf8')).workloads.find(w=>w.name===wl);
const evs = readFileSync(`../.corpus/${wl}.ndjson`, 'utf8').trim().split('\n').map(l => JSON.parse(l));
const invalid = new Set(JSON.parse(readFileSync('../.corpus/manifest.json','utf8')).invalid.map(x=>x.id));
const ctx = await C.load({});
const inst = await C.setup(ctx, `ws://127.0.0.1:7804/${wl}`, m, { timeoutMs: 60000 });
const got = new Set();
C.start(inst, { limit: evs.length }, { event: id => got.add(id), eose: () => console.log('eose at', got.size), error: e => console.log('err', e) }, { timeoutMs: 60000 });
await new Promise(r => setTimeout(r, Number(process.argv[4] ?? 8000)));
for (const e of evs) if (!got.has(e.id) && !invalid.has(e.id) && !m.expired_ids.includes(e.id)) console.log('missing valid', e.id, e.kind, e.created_at, JSON.stringify(e.tags.find(t=>t[0]==='expiration')), e.content.slice(0,40));
for (const e of evs) if (got.has(e.id) && m.expired_ids.includes(e.id)) console.log('accepted expired', e.id, e.kind, JSON.stringify(e.tags.filter(t=>t[0]==='expiration')));
process.exit(0);
